/* ── Инициализация SSD1306 ─────────────────────────────────────── */
static HAL_StatusTypeDef cmd(uint8_t c) {
    uint8_t buf[2] = {0x00, c};
    return HAL_I2C_Master_Transmit(_hi2c, SSD1306_I2C_ADDR, buf, 2, 10);
}

HAL_StatusTypeDef SSD1306_Init(I2C_HandleTypeDef *hi2c) {
    _hi2c = hi2c;
    HAL_Delay(100);

    static const uint8_t init_seq[] = {
        0xAE,       /* display off */
        0xD5, 0x80, /* clock div */
        0xA8, 0x3F, /* mux ratio 64 */
        0xD3, 0x00, /* display offset 0 */
        0x40,       /* start line 0 */
        0x8D, 0x14, /* charge pump on */
        0x20, 0x00, /* horizontal addr mode */
        0xA1,       /* seg remap */
        0xC8,       /* com scan dec */
        0xDA, 0x12, /* com pins */
        0x81, 0xCF, /* contrast */
        0xD9, 0xF1, /* precharge */
        0xDB, 0x40, /* vcomh */
        0xA4,       /* output follows RAM */
        0xA6,       /* normal (not inverted) */
        0xAF,       /* display on */
    };
    for (uint8_t i = 0; i < sizeof(init_seq); i++) {
        if (cmd(init_seq[i]) != HAL_OK) return HAL_ERROR;
    }
    SSD1306_Clear();
    SSD1306_Flush();
    return HAL_OK;
}

/* ── Фреймбуфер ────────────────────────────────────────────────── */
void SSD1306_Clear(void) {
    memset(ssd1306_fb, 0, sizeof(ssd1306_fb));
}

void SSD1306_SetPixel(uint8_t x, uint8_t y, uint8_t on) {
    if (x >= SSD1306_W || y >= SSD1306_H) return;
    uint8_t page = y >> 3;
    uint8_t bit  = y & 7;
    if (on) ssd1306_fb[page][x] |=  (1 << bit);
    else    ssd1306_fb[page][x] &= ~(1 << bit);
}

void SSD1306_DrawHLine(uint8_t x0, uint8_t x1, uint8_t y) {
    for (uint8_t x = x0; x <= x1; x++) SSD1306_SetPixel(x, y, 1);
}

void SSD1306_DrawVLine(uint8_t x, uint8_t y0, uint8_t y1) {
    for (uint8_t y = y0; y <= y1; y++) SSD1306_SetPixel(x, y, 1);
}

void SSD1306_DrawBar(uint8_t x, uint8_t y_top, uint8_t height) {
    for (uint8_t y = y_top; y < y_top + height && y < SSD1306_H; y++)
        SSD1306_SetPixel(x, y, 1);
}

/* ── Текст ─────────────────────────────────────────────────────── */
void SSD1306_DrawChar(uint8_t x, uint8_t page, char c) {
    if (c < 0x20 || c > 0x7A) c = ' ';
    const uint8_t *glyph = font5x7[c - 0x20];
    for (uint8_t col = 0; col < 5; col++) {
        if (x + col >= SSD1306_W) break;
        ssd1306_fb[page][x + col] = glyph[col];
    }
}

void SSD1306_DrawString(uint8_t x, uint8_t page, const char *str) {
    while (*str && x < SSD1306_W) {
        SSD1306_DrawChar(x, page, *str++);
        x += 6;
    }
}

/* ── Flush: FB → SSD1306 по страницам, DMA ────────────────────── */
/* Для простоты используем polling Transmit (DMA опционален) */
void SSD1306_Flush(void) {
    tx_buf[0] = 0x40; /* Co=0, D/C#=1 → поток данных */

    for (uint8_t page = 0; page < SSD1306_PAGES; page++) {
        /* Установить адрес страницы */
        uint8_t cmds[4] = {
            0x00,                       /* контрольный байт — команды */
            0xB0 | page,                /* page start */
            0x00,                       /* low col = 0 */
            0x10,                       /* high col = 0 */
        };
        HAL_I2C_Master_Transmit(_hi2c, SSD1306_I2C_ADDR,
                                cmds, 4, 10);

        /* Передать 128 пикселей страницы */
        memcpy(&tx_buf[1], ssd1306_fb[page], SSD1306_W);
        HAL_I2C_Master_Transmit(_hi2c, SSD1306_I2C_ADDR,
                                tx_buf, 1 + SSD1306_W, 20);
    }
}
